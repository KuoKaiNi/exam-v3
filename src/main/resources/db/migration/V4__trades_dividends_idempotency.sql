-- 官方除權息資料。source 是查到資料的主機，換成測試伺服器時不沿用。
-- cash_per_share、stock_per_thousand 為 NULL：證交所「權」「權息」的明細還沒查到。
CREATE TABLE ex_right (
    source              VARCHAR(200)   NOT NULL,
    market              VARCHAR(4)     NOT NULL,
    code                VARCHAR(10)    NOT NULL,
    ex_date             DATE           NOT NULL,
    kind                VARCHAR(10)    NOT NULL,
    cash_per_share      DECIMAL(20, 8),
    stock_per_thousand  DECIMAL(20, 8),
    fetched_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (source, code, ex_date)
);

-- 哪一年的除權息表已經抓過
CREATE TABLE ex_right_fetch (
    source      VARCHAR(200) NOT NULL,
    market      VARCHAR(4)   NOT NULL,
    fetch_year  INT          NOT NULL,
    fetched_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (source, market, fetch_year)
);

-- App 2.0 逾時重送、網頁重複送出：同一個 Idempotency-Key 只做一次，之後回同樣的結果
CREATE TABLE idempotency_key (
    idem_key       VARCHAR(100) NOT NULL PRIMARY KEY,
    request_hash   VARCHAR(64)  NOT NULL,
    status         INT          NOT NULL,
    response_body  CLOB,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL
);
