-- 2.0：每次買進、賣出各記一筆；持股（holding）只留代號、名稱、市場別。

CREATE TABLE trade (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    holding_id  BIGINT         NOT NULL,
    side        VARCHAR(4)     NOT NULL,
    trade_date  DATE           NOT NULL,
    shares      INT            NOT NULL,
    price       DECIMAL(10, 2) NOT NULL,
    version     INT            NOT NULL DEFAULT 1,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_trade_holding FOREIGN KEY (holding_id) REFERENCES holding (id) ON DELETE CASCADE,
    CONSTRAINT ck_trade_side CHECK (side IN ('BUY', 'SELL')),
    CONSTRAINT ck_trade_shares CHECK (shares BETWEEN 1 AND 999999),
    CONSTRAINT ck_trade_price CHECK (price > 0)
);
CREATE INDEX ix_trade_holding ON trade (holding_id, trade_date);

